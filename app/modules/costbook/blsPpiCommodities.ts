/** Latest observation for a series (most recent year/month). */
export function latestPpiObservation(seriesId: string): BlsPpiCommodityObservation | undefined {
  let best: BlsPpiCommodityObservation | undefined;
  for (const o of BLS_PPI_COMMODITY_OBSERVATIONS) {
    if (o.seriesId !== seriesId) continue;
    if (!best || o.year > best.year || (o.year === best.year && o.month > best.month)) best = o;
  }
  return best;
}

/** Observation for an exact year/month, or undefined if missing. */
export function ppiObservationAt(seriesId: string, year: number, month: number): BlsPpiCommodityObservation | undefined {
  return BLS_PPI_COMMODITY_OBSERVATIONS.find((o) => o.seriesId === seriesId && o.year === year && o.month === month);
}

/** Percent change between two index values. Throws on non-finite or zero baseline. */
export function ppiPercentChange(from: number, to: number): number {
  if (!Number.isFinite(from) || !Number.isFinite(to) || from === 0) throw new Error("PPI change requires finite, non-zero baseline");
  return ((to / from) - 1) * 100;
}

/**
 * Year-over-year percent change for the latest observation vs the same
 * month one year earlier. Returns undefined when either side is missing.
 */
export function ppiYearOverYear(seriesId: string): number | undefined {
  const latest = latestPpiObservation(seriesId);
  if (!latest) return undefined;
  const prior = ppiObservationAt(seriesId, latest.year - 1, latest.month);
  if (!prior) return undefined;
  return ppiPercentChange(prior.value, latest.value);
}

/**
 * Escalate an observed price by index movement: observed × (indexNow / indexThen).
 * The result is an *estimate* — callers must label it inferred, never observed.
 */
export function escalateByPpi(observedPrice: number, indexThen: number, indexNow: number): number {
  if (!Number.isFinite(observedPrice) || !Number.isFinite(indexThen) || !Number.isFinite(indexNow) || indexThen === 0)
    throw new Error("PPI escalation requires finite values and non-zero baseline");
  return observedPrice * (indexNow / indexThen);
}

/** Find the commodity series for a costbook material family (e.g. 'LUMBER'). */
export function ppiSeriesForMaterialFamily(materialFamily: string): BlsPpiCommoditySeries | undefined {
  const key = materialFamily.toUpperCase();
  return BLS_PPI_COMMODITY_SERIES.find((s) => s.materialFamily === key);
}
